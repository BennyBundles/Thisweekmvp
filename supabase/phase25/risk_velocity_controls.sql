-- Phase 25 — Risk & Velocity Controls
-- Canonical source record for the deployed Phase 25 risk layer; database objects were applied on 2026-09-19.
-- Application-level controls are subordinate to provider/program/bank controls.

begin;

create table if not exists public.tw_risk_policies (
  id uuid primary key default gen_random_uuid(),
  environment text not null check (environment in ('sandbox','production')),
  policy_version text not null,
  active boolean not null default false,
  rules jsonb not null,
  created_at timestamptz not null default now(),
  unique(environment, policy_version)
);

create unique index if not exists tw_risk_one_active_policy_per_env
  on public.tw_risk_policies(environment) where active;

create table if not exists public.tw_risk_user_controls (
  user_id uuid primary key references auth.users(id) on delete cascade,
  state text not null default 'normal'
    check (state in ('normal','restricted','frozen','closed')),
  reason_code text,
  expires_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.tw_risk_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  environment text not null check (environment in ('sandbox','production')),
  action text not null,
  amount_cents bigint not null default 0 check (amount_cents >= 0),
  idempotency_key text not null,
  decision text not null check (decision in ('allow','review','deny')),
  reason_code text not null,
  policy_id uuid references public.tw_risk_policies(id) on delete restrict,
  resource_ref text,
  safe_context jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique(user_id, action, idempotency_key)
);

create index if not exists tw_risk_events_velocity_idx
  on public.tw_risk_events(user_id, environment, action, created_at desc);

create table if not exists public.tw_risk_reviews (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  risk_event_id bigint not null unique references public.tw_risk_events(id) on delete cascade,
  state text not null default 'pending'
    check (state in ('pending','approved','denied','cancelled')),
  resolution_code text,
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);

do $$
declare t text;
begin
  foreach t in array array['tw_risk_policies','tw_risk_user_controls','tw_risk_events','tw_risk_reviews']
  loop
    execute format('alter table public.%I enable row level security',t);
    execute format('revoke all on table public.%I from public, anon, authenticated',t);
    execute format('grant select,insert,update,delete on table public.%I to service_role',t);
  end loop;
end $$;

