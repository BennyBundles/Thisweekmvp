create or replace function public.tw_release_drill_status(p_drill_id uuid)
returns jsonb
language sql
security definer
stable
set search_path = pg_catalog, public, auth
as $$
  with d as (
    select * from public.tw_release_drill_runs where id=p_drill_id
  ),
  terminal as (
    select e.*
    from public.tw_release_drill_events e
    where e.drill_id=p_drill_id and e.event_type in ('completed','failed')
    order by e.id desc limit 1
  )
  select case when not exists(select 1 from d) then
    jsonb_build_object('exists',false,'passed',false)
  else
    jsonb_build_object(
      'exists',true,
      'drillId',(select id from d),
      'drillType',(select drill_type from d),
      'releaseCandidateSha',(select release_candidate_sha from d),
      'terminal',exists(select 1 from terminal),
      'passed',coalesce((select outcome='pass' and event_type='completed' from terminal),false),
      'terminalEventId',(select id from terminal),
      'evidenceRef',(select evidence_ref from terminal)
    )
  end;
$$;

create or replace function public.tw_release_start_drill(
  p_staff_user_id uuid,
  p_drill_type text,
  p_release_candidate_sha text,
  p_scenario_key text,
  p_note text default null
)
returns uuid
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  v_role text;
  v_id uuid;
begin
  select coalesce(raw_app_meta_data->>'thisweek_role','') into v_role
  from auth.users where id=p_staff_user_id;
  if v_role not in ('risk_ops','admin') then raise exception 'risk_or_admin_role_required'; end if;
  if p_drill_type not in ('synthetic_incident','rollback') then raise exception 'invalid_drill_type'; end if;
  if coalesce(p_release_candidate_sha,'') !~ '^[0-9a-f]{7,64}$' then raise exception 'invalid_release_candidate_sha'; end if;
  if length(trim(coalesce(p_scenario_key,''))) < 3 then raise exception 'drill_scenario_required'; end if;

  insert into public.tw_release_drill_runs(
    drill_type,release_candidate_sha,scenario_key,started_by_staff_user_id,note
  ) values (
    p_drill_type,lower(p_release_candidate_sha),left(trim(p_scenario_key),120),p_staff_user_id,
    left(nullif(trim(coalesce(p_note,'')),''),1000)
  ) returning id into v_id;

  insert into public.tw_release_drill_events(
    drill_id,event_type,outcome,evidence_ref,safe_summary,staff_user_id
  ) values (v_id,'started',null,null,'drill_started',p_staff_user_id);

  return v_id;
end;
$$;

create or replace function public.tw_release_finish_drill(
  p_staff_user_id uuid,
  p_drill_id uuid,
  p_passed boolean,
  p_evidence_ref text,
  p_safe_summary text default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  v_role text;
begin
  select coalesce(raw_app_meta_data->>'thisweek_role','') into v_role
  from auth.users where id=p_staff_user_id;
  if v_role not in ('risk_ops','admin') then raise exception 'risk_or_admin_role_required'; end if;
  if not exists(select 1 from public.tw_release_drill_runs where id=p_drill_id) then raise exception 'drill_not_found'; end if;
  if exists(select 1 from public.tw_release_drill_events where drill_id=p_drill_id and event_type in ('completed','failed')) then
    raise exception 'drill_already_terminal';
  end if;
  if length(trim(coalesce(p_evidence_ref,''))) < 3 then raise exception 'drill_evidence_required'; end if;

  insert into public.tw_release_drill_events(
    drill_id,event_type,outcome,evidence_ref,safe_summary,staff_user_id
  ) values (
    p_drill_id,
    case when p_passed then 'completed' else 'failed' end,
    case when p_passed then 'pass' else 'fail' end,
    left(trim(p_evidence_ref),500),
    left(nullif(trim(coalesce(p_safe_summary,'')),''),1000),
    p_staff_user_id
  );

  return public.tw_release_drill_status(p_drill_id);
end;
$$;

