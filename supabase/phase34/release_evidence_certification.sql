-- Phase 34 — Release Evidence & Sandbox Certification
-- Evidence is append-only. Production money remains governed by Phase 31's fail-closed interlock.

begin;

create table if not exists public.tw_release_certification_requirements (
  requirement_key text primary key,
  provider text,
  group_key text not null,
  label text not null,
  required_for_sandbox_e2e boolean not null default true,
  active boolean not null default true,
  sort_order integer not null default 100,
  updated_at timestamptz not null default now(),
  check (provider is null or provider in ('plaid','unit','pinwheel','method','thisweek'))
);

create table if not exists public.tw_release_certification_runs (
  id uuid primary key default gen_random_uuid(),
  environment text not null default 'sandbox' check (environment='sandbox'),
  release_candidate_sha text not null check (release_candidate_sha ~ '^[0-9a-f]{7,64}$'),
  checklist_version text not null default '2026-09-v1',
  started_by_staff_user_id uuid not null references auth.users(id) on delete restrict,
  note text,
  started_at timestamptz not null default now()
);

create table if not exists public.tw_release_drill_runs (
  id uuid primary key default gen_random_uuid(),
  drill_type text not null check (drill_type in ('synthetic_incident','rollback')),
  environment text not null default 'sandbox' check (environment='sandbox'),
  release_candidate_sha text not null check (release_candidate_sha ~ '^[0-9a-f]{7,64}$'),
  scenario_key text not null,
  started_by_staff_user_id uuid not null references auth.users(id) on delete restrict,
  note text,
  started_at timestamptz not null default now()
);

create table if not exists public.tw_release_drill_events (
  id bigint generated by default as identity primary key,
  drill_id uuid not null references public.tw_release_drill_runs(id) on delete restrict,
  event_type text not null check (event_type in ('started','step','completed','failed')),
  outcome text check (outcome is null or outcome in ('pass','fail')),
  evidence_ref text,
  safe_summary text,
  staff_user_id uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  check (
    (event_type in ('completed','failed') and outcome in ('pass','fail') and length(trim(coalesce(evidence_ref,''))) >= 3)
    or
    (event_type in ('started','step'))
  )
);

create table if not exists public.tw_release_certification_receipts (
  id bigint generated by default as identity primary key,
  run_id uuid not null references public.tw_release_certification_runs(id) on delete restrict,
  requirement_key text not null references public.tw_release_certification_requirements(requirement_key) on delete restrict,
  outcome text not null check (outcome in ('pass','fail')),
  evidence_ref text not null check (length(trim(evidence_ref)) >= 3),
  safe_summary text,
  drill_id uuid references public.tw_release_drill_runs(id) on delete restrict,
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata)='object'),
  staff_user_id uuid not null references auth.users(id) on delete restrict,
  supersedes_receipt_id bigint references public.tw_release_certification_receipts(id) on delete restrict,
  created_at timestamptz not null default now(),
  check (supersedes_receipt_id is null or supersedes_receipt_id <> id)
);

create table if not exists public.tw_release_gate_evidence_requirements (
  gate_key text not null references public.tw_release_gates(gate_key) on delete restrict,
  evidence_key text not null,
  label text not null,
  source_type text not null check (source_type in ('manual','derived')),
  sort_order integer not null default 100,
  active boolean not null default true,
  updated_at timestamptz not null default now(),
  primary key (gate_key,evidence_key)
);

create table if not exists public.tw_release_gate_evidence (
  id bigint generated by default as identity primary key,
  gate_key text not null,
  evidence_key text not null,
  environment text not null check (environment in ('sandbox','production')),
  provider text,
  outcome text not null check (outcome in ('pass','fail')),
  evidence_ref text not null check (length(trim(evidence_ref)) >= 3),
  safe_summary text,
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata)='object'),
  staff_user_id uuid not null references auth.users(id) on delete restrict,
  supersedes_evidence_id bigint references public.tw_release_gate_evidence(id) on delete restrict,
  created_at timestamptz not null default now(),
  foreign key (gate_key,evidence_key)
    references public.tw_release_gate_evidence_requirements(gate_key,evidence_key) on delete restrict,
  check (provider is null or provider in ('plaid','unit','pinwheel','method','thisweek')),
  check (supersedes_evidence_id is null or supersedes_evidence_id <> id)
);

