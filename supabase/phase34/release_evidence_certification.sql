create or replace function public.tw_release_record_certification_receipt(
  p_staff_user_id uuid,
  p_run_id uuid,
  p_requirement_key text,
  p_outcome text,
  p_evidence_ref text,
  p_safe_summary text default null,
  p_drill_id uuid default null,
  p_metadata jsonb default '{}'::jsonb,
  p_supersedes_receipt_id bigint default null
)
returns bigint
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  v_role text;
  v_id bigint;
  v_req public.tw_release_certification_requirements%rowtype;
  v_drill jsonb;
begin
  select coalesce(raw_app_meta_data->>'thisweek_role','') into v_role
  from auth.users where id=p_staff_user_id;
  if v_role not in ('risk_ops','admin') then raise exception 'risk_or_admin_role_required'; end if;
  if not exists(select 1 from public.tw_release_certification_runs where id=p_run_id) then raise exception 'certification_run_not_found'; end if;
  select * into v_req from public.tw_release_certification_requirements
  where requirement_key=p_requirement_key and active=true;
  if v_req.requirement_key is null then raise exception 'certification_requirement_not_found'; end if;
  if p_outcome not in ('pass','fail') then raise exception 'invalid_certification_outcome'; end if;
  if length(trim(coalesce(p_evidence_ref,''))) < 3 then raise exception 'certification_evidence_required'; end if;
  if p_metadata is null or jsonb_typeof(p_metadata) <> 'object' then raise exception 'certification_metadata_must_be_object'; end if;

  if p_requirement_key in ('synthetic_incident_drill','rollback_validation') and p_outcome='pass' then
    if p_drill_id is null then raise exception 'passing_drill_receipt_required'; end if;
    v_drill:=public.tw_release_drill_status(p_drill_id);
    if coalesce((v_drill->>'passed')::boolean,false) is not true then raise exception 'passing_drill_receipt_required'; end if;
    if p_requirement_key='synthetic_incident_drill' and v_drill->>'drillType' <> 'synthetic_incident' then raise exception 'wrong_drill_type'; end if;
    if p_requirement_key='rollback_validation' and v_drill->>'drillType' <> 'rollback' then raise exception 'wrong_drill_type'; end if;
  end if;

  if p_supersedes_receipt_id is not null and not exists(
    select 1 from public.tw_release_certification_receipts
    where id=p_supersedes_receipt_id and run_id=p_run_id and requirement_key=p_requirement_key
  ) then raise exception 'superseded_receipt_mismatch'; end if;

  insert into public.tw_release_certification_receipts(
    run_id,requirement_key,outcome,evidence_ref,safe_summary,drill_id,metadata,staff_user_id,supersedes_receipt_id
  ) values (
    p_run_id,p_requirement_key,p_outcome,left(trim(p_evidence_ref),500),
    left(nullif(trim(coalesce(p_safe_summary,'')),''),1000),p_drill_id,p_metadata,p_staff_user_id,p_supersedes_receipt_id
  ) returning id into v_id;
  return v_id;
end;
$$;

create or replace function public.tw_release_certification_status(p_run_id uuid)
returns jsonb
language sql
security definer
stable
set search_path = pg_catalog, public, auth
as $$
  with req as (
    select * from public.tw_release_certification_requirements
    where active=true and required_for_sandbox_e2e=true
  ),
  latest as (
    select distinct on (r.requirement_key)
      r.requirement_key,r.outcome,r.evidence_ref,r.drill_id,r.created_at,r.id
    from public.tw_release_certification_receipts r
    where r.run_id=p_run_id
    order by r.requirement_key,r.created_at desc,r.id desc
  ),
  rows as (
    select
      q.requirement_key,q.provider,q.group_key,q.label,q.sort_order,
      l.outcome,l.evidence_ref,l.drill_id,l.created_at,l.id as receipt_id,
      coalesce(l.outcome='pass',false) as passed
    from req q left join latest l using(requirement_key)
  ),
  run as (
    select * from public.tw_release_certification_runs where id=p_run_id
  )
  select case when not exists(select 1 from run) then
    jsonb_build_object('exists',false,'passed',false)
  else jsonb_build_object(
    'exists',true,
    'runId',(select id from run),
    'releaseCandidateSha',(select release_candidate_sha from run),
    'checklistVersion',(select checklist_version from run),
    'requiredCount',(select count(*) from rows),
    'passedCount',(select count(*) from rows where passed),
    'failedCount',(select count(*) from rows where outcome='fail'),
    'missing',coalesce((select jsonb_agg(requirement_key order by sort_order) from rows where outcome is null),'[]'::jsonb),
    'passed',coalesce((select bool_and(passed) from rows),false) and exists(select 1 from rows),
    'requirements',coalesce((select jsonb_agg(jsonb_build_object(
      'requirementKey',requirement_key,'provider',provider,'group',group_key,'label',label,
      'outcome',outcome,'evidenceRef',evidence_ref,'drillId',drill_id,'receiptId',receipt_id,'recordedAt',created_at
    ) order by sort_order) from rows),'[]'::jsonb)
  ) end;
$$;

create or replace function public.tw_release_record_gate_evidence(
  p_staff_user_id uuid,
  p_gate_key text,
  p_evidence_key text,
  p_environment text,
  p_outcome text,
  p_evidence_ref text,
  p_safe_summary text default null,
  p_provider text default null,
  p_metadata jsonb default '{}'::jsonb,
  p_supersedes_evidence_id bigint default null
)
returns bigint
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  v_role text;
  v_source text;
  v_id bigint;
begin
  select coalesce(raw_app_meta_data->>'thisweek_role','') into v_role
  from auth.users where id=p_staff_user_id;
  if v_role is distinct from 'admin' then raise exception 'admin_role_required'; end if;

  select source_type into v_source
  from public.tw_release_gate_evidence_requirements
  where gate_key=p_gate_key and evidence_key=p_evidence_key and active=true;
  if v_source is null then raise exception 'release_evidence_requirement_not_found'; end if;
  if v_source <> 'manual' then raise exception 'derived_evidence_cannot_be_manually_recorded'; end if;
  if p_environment not in ('sandbox','production') then raise exception 'invalid_evidence_environment'; end if;
  if p_outcome not in ('pass','fail') then raise exception 'invalid_evidence_outcome'; end if;
  if length(trim(coalesce(p_evidence_ref,''))) < 3 then raise exception 'release_evidence_ref_required'; end if;
  if p_provider is not null and p_provider not in ('plaid','unit','pinwheel','method','thisweek') then raise exception 'invalid_evidence_provider'; end if;
  if p_metadata is null or jsonb_typeof(p_metadata) <> 'object' then raise exception 'release_evidence_metadata_must_be_object'; end if;

  if p_supersedes_evidence_id is not null and not exists(
    select 1 from public.tw_release_gate_evidence
    where id=p_supersedes_evidence_id and gate_key=p_gate_key and evidence_key=p_evidence_key
  ) then raise exception 'superseded_evidence_mismatch'; end if;

  insert into public.tw_release_gate_evidence(
    gate_key,evidence_key,environment,provider,outcome,evidence_ref,safe_summary,metadata,
    staff_user_id,supersedes_evidence_id
  ) values (
    p_gate_key,p_evidence_key,p_environment,p_provider,p_outcome,left(trim(p_evidence_ref),500),
    left(nullif(trim(coalesce(p_safe_summary,'')),''),1000),p_metadata,p_staff_user_id,p_supersedes_evidence_id
  ) returning id into v_id;
  return v_id;
end;
$$;

create or replace function public.tw_release_derived_evidence_pass(p_evidence_key text)
returns boolean
language plpgsql
security definer
stable
set search_path = pg_catalog, public, auth
as $$
declare
  v_status jsonb;
begin
  if p_evidence_key='sandbox_certification_passed' then
    return exists(
      select 1 from public.tw_release_certification_runs r
      where coalesce((public.tw_release_certification_status(r.id)->>'passed')::boolean,false)=true
    );
  elsif p_evidence_key='rollback_drill_passed' then
    return exists(
      select 1 from public.tw_release_drill_runs d
      where d.drill_type='rollback'
        and coalesce((public.tw_release_drill_status(d.id)->>'passed')::boolean,false)=true
    );
  elsif p_evidence_key='synthetic_incident_drill_passed' then
    return exists(
      select 1 from public.tw_release_drill_runs d
      where d.drill_type='synthetic_incident'
        and coalesce((public.tw_release_drill_status(d.id)->>'passed')::boolean,false)=true
    );
  elsif p_evidence_key='staff_coverage_current' then
    return
      exists(select 1 from auth.users where coalesce(raw_app_meta_data->>'thisweek_role','')='admin')
      and exists(select 1 from auth.users where coalesce(raw_app_meta_data->>'thisweek_role','') in ('risk_ops','admin'))
      and exists(select 1 from auth.users where coalesce(raw_app_meta_data->>'thisweek_role','') in ('support_ops','admin'));
  elsif p_evidence_key='notification_channel_healthy' then
    return exists(
      select 1 from public.tw_ops_notification_channel_status
      where channel_key='external_webhook' and configured=true and state='healthy'
    );
  elsif p_evidence_key='production_risk_policy_active' then
    return exists(select 1 from public.tw_risk_policies where environment='production' and active=true);
  elsif p_evidence_key in ('production_legal_set_active','production_retention_policy_active','sensitive_access_audit_active') then
    v_status:=public.tw_release_status();
    if p_evidence_key='production_legal_set_active' then
      return coalesce((v_status->>'productionLegalSetActive')::boolean,false);
    elsif p_evidence_key='production_retention_policy_active' then
      return coalesce((v_status->>'productionRetentionPolicyActive')::boolean,false);
    else
      return coalesce((v_status->>'sensitiveAccessAuditActive')::boolean,false);
    end if;
  end if;
  return false;
end;
$$;

create or replace function public.tw_release_gate_evidence_status(p_gate_key text)
returns jsonb
language sql
security definer
stable
set search_path = pg_catalog, public, auth
as $$
  with req as (
    select *
    from public.tw_release_gate_evidence_requirements
    where gate_key=p_gate_key and active=true
  ),
  latest_manual as (
    select distinct on (e.evidence_key)
      e.evidence_key,e.outcome,e.evidence_ref,e.created_at,e.id
    from public.tw_release_gate_evidence e
    where e.gate_key=p_gate_key
    order by e.evidence_key,e.created_at desc,e.id desc
  ),
  evaluated as (
    select
      r.evidence_key,r.label,r.source_type,r.sort_order,
      case
        when r.source_type='derived' then public.tw_release_derived_evidence_pass(r.evidence_key)
        else coalesce(m.outcome='pass',false)
      end as satisfied,
      m.outcome,m.evidence_ref,m.created_at,m.id
    from req r left join latest_manual m using(evidence_key)
  )
  select jsonb_build_object(
    'gateKey',p_gate_key,
    'requiredCount',(select count(*) from evaluated),
    'satisfiedCount',(select count(*) from evaluated where satisfied),
    'ready',coalesce((select bool_and(satisfied) from evaluated),false) and exists(select 1 from evaluated),
    'requirements',coalesce((select jsonb_agg(jsonb_build_object(
      'evidenceKey',evidence_key,'label',label,'sourceType',source_type,'satisfied',satisfied,
      'outcome',outcome,'evidenceRef',evidence_ref,'recordedAt',created_at,'receiptId',id
    ) order by sort_order) from evaluated),'[]'::jsonb)
  );
$$;

create or replace function public.tw_release_readiness_report()
returns jsonb
language sql
security definer
stable
set search_path = pg_catalog, public, auth
as $$
  with gates as (
    select
      g.gate_key,g.category,g.label,g.required_for_live_money,g.verified,g.verified_at,g.evidence_ref,
      public.tw_release_gate_evidence_status(g.gate_key) as evidence
    from public.tw_release_gates g
    order by g.category,g.gate_key
  ),
  latest_cert as (
    select r.*,public.tw_release_certification_status(r.id) as status
    from public.tw_release_certification_runs r
    order by r.started_at desc
    limit 1
  )
  select jsonb_build_object(
    'generatedAt',now(),
    'releaseStatus',public.tw_release_status(),
    'latestSandboxCertification',(select status from latest_cert),
    'gates',coalesce((select jsonb_agg(jsonb_build_object(
      'gateKey',gate_key,'category',category,'label',label,'required',required_for_live_money,
      'verified',verified,'verifiedAt',verified_at,'evidenceRef',evidence_ref,'evidence',evidence
    )) from gates),'[]'::jsonb),
    'blockingGateKeys',coalesce((select jsonb_agg(gate_key) from gates
      where required_for_live_money and (verified=false or coalesce((evidence->>'ready')::boolean,false)=false)
    ),'[]'::jsonb)
  );
$$;

create or replace function public.tw_release_set_gate(
  p_staff_user_id uuid,
  p_gate_key text,
  p_verified boolean,
  p_evidence_ref text,
  p_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  v_gate public.tw_release_gates%rowtype;
  v_role text;
  v_evidence jsonb;
begin
  select coalesce(raw_app_meta_data->>'thisweek_role','')
  into v_role
  from auth.users
  where id=p_staff_user_id;

  if v_role is distinct from 'admin' then
    raise exception 'admin_role_required';
  end if;

  select * into v_gate
  from public.tw_release_gates
  where gate_key=p_gate_key
  for update;

  if v_gate.gate_key is null then raise exception 'release_gate_not_found'; end if;
  if coalesce(length(trim(p_evidence_ref)),0)<3 then raise exception 'release_gate_evidence_required'; end if;

  if p_verified then
    v_evidence:=public.tw_release_gate_evidence_status(p_gate_key);
    if coalesce((v_evidence->>'ready')::boolean,false) is not true then
      raise exception 'release_gate_supporting_evidence_missing';
    end if;
  end if;

  insert into public.tw_release_gate_events(
    gate_key,staff_user_id,previous_verified,next_verified,evidence_ref,note
  ) values (
    v_gate.gate_key,p_staff_user_id,v_gate.verified,p_verified,
    left(trim(p_evidence_ref),500),left(nullif(trim(coalesce(p_note,'')),''),1000)
  );

  update public.tw_release_gates
  set verified=p_verified,
      verified_by_staff_user_id=p_staff_user_id,
      verified_at=case when p_verified then now() else null end,
      evidence_ref=left(trim(p_evidence_ref),500),
      note=left(nullif(trim(coalesce(p_note,'')),''),1000),
      updated_at=now()
  where gate_key=v_gate.gate_key;

  return jsonb_build_object(
    'gateKey',v_gate.gate_key,
    'verified',p_verified,
    'supportingEvidence',v_evidence,
    'updatedBy',p_staff_user_id,
    'updatedAt',now()
  );
end;
$$;

