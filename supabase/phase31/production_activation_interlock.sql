create or replace function public.tw_release_status()
returns jsonb
language sql
security definer
stable
set search_path = pg_catalog, public, auth
as $$
  with manual as (
    select
      coalesce(bool_and(verified) filter (where required_for_live_money),false) as manual_ready,
      coalesce(
        jsonb_agg(
          jsonb_build_object(
            'gateKey',gate_key,
            'category',category,
            'label',label,
            'required',required_for_live_money,
            'verified',verified,
            'verifiedAt',verified_at,
            'evidenceRef',evidence_ref,
            'note',note
          ) order by category,gate_key
        ),
        '[]'::jsonb
      ) as gates
    from public.tw_release_gates
  ),
  derived as (
    select
      exists(select 1 from public.tw_risk_policies where environment='production' and active=true)
        as production_risk_active,
      exists(
        select 1 from public.tw_ops_notification_channel_status
        where channel_key='external_webhook' and configured=true and state='healthy'
      ) as notification_channel_healthy,
      exists(
        select 1 from auth.users
        where coalesce(raw_app_meta_data->>'thisweek_role','')='admin'
      ) as admin_staff_exists,
      exists(
        select 1 from auth.users
        where coalesce(raw_app_meta_data->>'thisweek_role','') in ('risk_ops','admin')
      ) as risk_staff_exists,
      exists(
        select 1 from auth.users
        where coalesce(raw_app_meta_data->>'thisweek_role','') in ('support_ops','admin')
      ) as support_staff_exists
  )
  select jsonb_build_object(
    'manualGatesReady',manual.manual_ready,
    'productionRiskPolicyActive',derived.production_risk_active,
    'notificationChannelHealthy',derived.notification_channel_healthy,
    'staffCoverage',jsonb_build_object(
      'admin',derived.admin_staff_exists,
      'risk',derived.risk_staff_exists,
      'support',derived.support_staff_exists
    ),
    'liveMoneyReady',
      manual.manual_ready
      and derived.production_risk_active
      and derived.notification_channel_healthy
      and derived.admin_staff_exists
      and derived.risk_staff_exists
      and derived.support_staff_exists,
    'gates',manual.gates
  )
  from manual cross join derived;
$$;

create or replace function public.tw_release_money_enabled()
returns boolean
language sql
security definer
stable
set search_path = pg_catalog, public, auth
as $$
  select coalesce((public.tw_release_status()->>'liveMoneyReady')::boolean,false);
$$;

create or replace function public.tw_release_set_gate(
  p_staff_user_id uuid,
  p_gate_key text,
  p_verified boolean,
  p_evidence_ref text,
  p_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $$
declare
  v_gate public.tw_release_gates%rowtype;
  v_role text;
begin
  select coalesce(raw_app_meta_data->>'thisweek_role','')
  into v_role
  from auth.users
  where id=p_staff_user_id;

  if v_role is distinct from 'admin' then
    raise exception 'admin_role_required';
  end if;

  select * into v_gate
  from public.tw_release_gates
  where gate_key=p_gate_key
  for update;

  if v_gate.gate_key is null then raise exception 'release_gate_not_found'; end if;
  if coalesce(length(trim(p_evidence_ref)),0)<3 then raise exception 'release_gate_evidence_required'; end if;

  insert into public.tw_release_gate_events(
    gate_key,staff_user_id,previous_verified,next_verified,evidence_ref,note
  ) values (
    v_gate.gate_key,p_staff_user_id,v_gate.verified,p_verified,
    left(trim(p_evidence_ref),500),left(nullif(trim(coalesce(p_note,'')),''),1000)
  );

  update public.tw_release_gates
  set verified=p_verified,
      verified_by_staff_user_id=p_staff_user_id,
      verified_at=case when p_verified then now() else null end,
      evidence_ref=left(trim(p_evidence_ref),500),
      note=left(nullif(trim(coalesce(p_note,'')),''),1000),
      updated_at=now()
  where gate_key=v_gate.gate_key;

  return jsonb_build_object(
    'gateKey',v_gate.gate_key,
    'verified',p_verified,
    'updatedBy',p_staff_user_id,
    'updatedAt',now()
  );
end;
$$;

