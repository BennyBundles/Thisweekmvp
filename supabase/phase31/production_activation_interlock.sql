create table if not exists public.tw_release_gates (
  gate_key text primary key,
  category text not null
    check (category in ('auth','providers','risk','operations','legal','commercial')),
  label text not null,
  required_for_live_money boolean not null default true,
  verified boolean not null default false,
  verified_by_staff_user_id uuid references auth.users(id) on delete set null,
  verified_at timestamptz,
  evidence_ref text,
  note text,
  updated_at timestamptz not null default now()
);

create table if not exists public.tw_release_gate_events (
  id bigint generated by default as identity primary key,
  gate_key text not null references public.tw_release_gates(gate_key) on delete restrict,
  staff_user_id uuid not null references auth.users(id) on delete restrict,
  previous_verified boolean not null,
  next_verified boolean not null,
  evidence_ref text,
  note text,
  created_at timestamptz not null default now()
);

